#!/usr/bin/env python3
"""Writes src/unit-words.typ from the unit table (needs cargo and typst); --check only compares."""
import json, subprocess, sys, unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/unit-words.typ"

HEADER = """\
// The `units` module (`#import units: km, mA, s`): units as names, so math knows them without guessing: $4 mA$ is 4
// milliamperes, never a variable. Each is the unit's text labelled <solveng-unit-word>, set upright, and means what
// the worksheet where it's used has under that name (an error with builtin-units: false, unless the option units
// defines it). Single letters need a hash in math ($1#s$): Typst reads a lone letter as a letter.
// Left out: names Typst already has globally or in math (h, min, deg, …) and as, the cast.
// Generated by scripts/unit-words.py from the unit table: every unit and every prefixed one.
"""


def main():
    names = subprocess.run(["cargo", "run", "-q", "-p", "solveng-core", "--example", "unit_names"], cwd=ROOT, check=True, capture_output=True, text=True).stdout.split()
    # identifiers in their own spelling (not Ω's compatibility sign), never the cast
    names = [n for n in names if n.isidentifier() and unicodedata.normalize("NFC", n) == n and n != "as"]
    taken = json.loads(subprocess.run(["typst", "eval", "--format", "json", f"{json.dumps(names)}.filter(n => n in dictionary(std) or n in dictionary(math) or n in dictionary(sym))".replace("[", "(").replace("]", ",)")], cwd=ROOT, check=True, capture_output=True, text=True).stdout)
    words = sorted(n for n in names if n not in taken)
    text = HEADER + "\n" + "".join(f'#let {n} = [#"{n}"<solveng-unit-word>]\n' for n in words)
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit("src/unit-words.typ is out of date: run scripts/unit-words.py")
        return
    OUT.write_text(text)


main()
