#!/usr/bin/env python3
"""Generate lexical unit definitions and their explicit display functions."""
import json, subprocess, sys, unicodedata
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/unit-words.typ"
BASES = {"m": "m", "kg": "kg", "s": "s", "A": "A", "K": "K", "mol": "mol", "cd": "cd"}
# symbols that are no Typst identifiers, bound under a name: #percent shows as %
NAMED = {"%": "percent", "‰": "permille"}
IDENTITIES = {"m": "length", "kg": "mass", "s": "time", "A": "electric-current", "K": "temperature", "mol": "amount-of-substance", "cd": "luminous-intensity"}
def main():
    data = subprocess.run(["cargo", "run", "-q", "-p", "solveng-core", "--example", "unit_definitions"], cwd=ROOT, check=True, capture_output=True, text=True).stdout
    text = '// Generated by scripts/unit-words.py; imports retain their values in every worksheet.\n#import "operation.typ": base-unit, unit\n\n'
    for name, identity in IDENTITIES.items():
        text += f'#let {name} = base-unit("{identity}", display: () => math.upright("{name}"))\n'
    text += "\n"
    for row in map(json.loads, data.splitlines()):
        name = NAMED.get(row["name"], row["name"])
        if not name.isidentifier() or unicodedata.normalize("NFC", name) != name or name in BASES or name == "as": continue
        text += f'#let {name} = unit(${row["expression"]}$, display: () => math.upright({json.dumps(row["display"], ensure_ascii=False)}))\n'
    if "--check" in sys.argv:
        if OUT.read_text() != text: sys.exit("unit definitions are out of date")
    else: OUT.write_text(text)
main()
