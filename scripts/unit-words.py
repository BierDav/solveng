#!/usr/bin/env python3
"""Writes src/unit-words.typ from the unit table (needs cargo and typst); --check only compares."""
import json, subprocess, sys, unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/unit-words.typ"

HEADER = """\
/// Shorthands for solveng's built-in units: every unit and every prefixed one under its name (`km`, `mA`, `kΩ`, `s`).
///
/// Import only the ones you use, where you use them: `#import units: km, mA`. Typst imports are lexical, so they
/// apply to that file or block and the ones nested in it; nothing comes along with `#import "@preview/solveng:1.0.0": *`.
///
/// A shorthand is just the unit's name, read through the units in effect where it's used: a worksheet's `units`
/// redefining it (`km: "s"`) or hiding it (`km: none`) and `builtin-units: false` apply. Single letters are math
/// symbols in Typst, so `#s` reaches the shorthand; otherwise write `"s"`. Quoted units and `unit("…")` keep working.
/// Names Typst defines globally, like `h`, aren't in the module: write `"h"`. Typst's math names (`min`, `deg`) are,
/// for when you want them read as units.
///
/// ```typ
/// #import units: km, min, s
/// #show: worksheet
/// $d := 3 km$, $t := 2 min$, $v := d / t -> km/#s$
/// ```

// Generated by scripts/unit-words.py from the unit table; left out: names of Typst's global scope (h, v), which
// `#import units: *` would hide in code too, as (the cast) and spellings of other names (Omega for Ω).
"""


def main():
    names = subprocess.run(["cargo", "run", "-q", "-p", "solveng-core", "--example", "unit_names"], cwd=ROOT, check=True, capture_output=True, text=True).stdout.split()
    # identifiers in their own spelling (not Ω's compatibility sign), never the cast
    names = [n for n in names if n.isidentifier() and unicodedata.normalize("NFC", n) == n and n != "as"]
    taken = json.loads(subprocess.run(["typst", "eval", "--format", "json", f"{json.dumps(names)}.filter(n => n in dictionary(std))".replace("[", "(").replace("]", ",)")], cwd=ROOT, check=True, capture_output=True, text=True).stdout)
    words = sorted(n for n in names if n not in taken)
    text = HEADER + "\n" + "".join(f'#let {n} = [#"{n}"<solveng-unit-word>]\n' for n in words)
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit("src/unit-words.typ is out of date: run scripts/unit-words.py")
        return
    OUT.write_text(text)


main()
